"""Two-wide sanitary fixtures, shared original porcelain materials and one controller drop."""
from copy import deepcopy
import json
from create_bathroom_statue_assets import ROOT, ASSETS, DATA, TOILET, URINAL, solid_model, write_json
from create_tall_bathroom_assets import TOILET_CLOSED, TOILET_OPEN, ADULT


def widened(parts):
    value = deepcopy(parts)
    for part in value:
        part[0][0] *= 2
        part[0][3] *= 2
        # Narrow the sanitary body by 12.5%, keeping cubicle walls and doors intact.
        if part[1] in ('porcelain', 'seat', 'drain'):
            part[0][0] = 16 + (part[0][0]-16)*0.875
            part[0][3] = 16 + (part[0][3]-16)*0.875
    return value


CLOSED = widened(TOILET_CLOSED)
OPENED = widened(TOILET_OPEN)
# Two half-width leaves fold against opposite walls, keeping the original one-block depth.
OPENED += [([28, 0, 1, 30, 32, 15], 'partition'), ([27.625, 13.5, 12, 28, 14.5, 13], 'chrome')]
FIXTURES = {
    'toilet': (CLOSED, OPENED, 2),
    'adult_men_urinal': (widened(ADULT), widened(ADULT), 2),
    'men_urinal': (widened(URINAL), widened(URINAL), 1),
    'standalone_toilet': (widened(TOILET[2:]), widened(TOILET[2:]), 1),
}


def clip(model, column, half):
    value = deepcopy(model)
    value['elements'] = []
    for original in model['elements']:
        e = deepcopy(original)
        for axis, index, negative, positive in ((0, column, 'west', 'east'), (1, half, 'down', 'up')):
            low, high = index*16, index*16+16
            if e['to'][axis] <= low or e['from'][axis] >= high:
                e['faces'] = {}
                break
            if e['from'][axis] < low: e['faces'].pop(negative, None)
            if e['to'][axis] > high: e['faces'].pop(positive, None)
            e['from'][axis] = max(low, e['from'][axis])-low
            e['to'][axis] = min(high, e['to'][axis])-low
        if e['faces']: value['elements'].append(e)
    return value


def main():
    constants = {'TOILET_CLOSED': CLOSED, 'TOILET_OPEN': OPENED, 'ADULT_URINAL': FIXTURES['adult_men_urinal'][0]}
    for class_name, geometry in (('TallBathroomShapes', constants), ('WideBathroomShapes', {
            'CHILD_URINAL': FIXTURES['men_urinal'][0], 'STANDALONE_TOILET': FIXTURES['standalone_toilet'][0]})):
        java = ['package net.nicomar2009.lsmmod.block;', '', '/** Generated by tools/create_wide_bathroom_assets.py. */',
                f'public final class {class_name} {{', f'    private {class_name}() {{}}']
        for name, parts in geometry.items():
            java += [f'    public static final double[][] {name} = {{']
            java += ['        {'+', '.join(str(v) for v in p[0])+'},' for p in parts]
            java += ['    };']
        java += ['}']
        (ROOT / f'src/main/java/net/nicomar2009/lsmmod/block/{class_name}.java').write_text('\n'.join(java)+'\n')
    for block_id, (closed, opened, height) in FIXTURES.items():
        variants = {}
        for is_open, parts in ((False, closed), (True, opened)) if height == 2 else ((False, closed),):
            mesh = solid_model(parts)
            for half in range(height):
                half_name = 'upper' if half else 'lower'
                for column in range(2):
                    name = f'{block_id}_{half_name}_{"open" if is_open else "closed"}_column_{column}'
                    write_json(ASSETS / f'models/block/{name}.json', clip(mesh, column, half))
                    for facing, angle in (('north', 0), ('east', 90), ('south', 180), ('west', 270)):
                        key = f'column={column},facing={facing}'
                        if height == 2: key += f',half={half_name},open={str(is_open).lower()}'
                        variants[key] = {'model': f'lsmmod:block/{name}', 'y': angle}
                if height == 2:
                    # Legacy model paths remain valid, but no longer span outside their cell.
                    write_json(ASSETS / f'models/block/{block_id}_{half_name}_{"open" if is_open else "closed"}.json',
                               {'parent': f'lsmmod:block/{block_id}_{half_name}_{"open" if is_open else "closed"}_column_0'})
        write_json(ASSETS / f'blockstates/{block_id}.json', {'variants': variants})
        write_json(ASSETS / f'models/block/{block_id}.json', {'parent': f'lsmmod:block/{block_id}_lower_closed_column_0'})
        item = solid_model(closed)
        for e in item['elements']:
            e['from'] = [e['from'][0]/2, e['from'][1]/2, 4+e['from'][2]/2]
            e['to'] = [e['to'][0]/2, e['to'][1]/2, 4+e['to'][2]/2]
        write_json(ASSETS / f'models/item/{block_id}.json', item)
        write_json(ASSETS / f'items/{block_id}.json', {'model': {'type': 'minecraft:model', 'model': f'lsmmod:item/{block_id}'}})
        controller = {'column': '0'}
        if height == 2: controller['half'] = 'lower'
        write_json(DATA / f'lsmmod/loot_table/blocks/{block_id}.json', {'type': 'minecraft:block', 'pools': [{'rolls': 1,
            'conditions': [{'condition': 'minecraft:survives_explosion'}, {'condition': 'minecraft:block_state_property',
                'block': f'lsmmod:{block_id}', 'properties': controller}],
            'entries': [{'type': 'minecraft:item', 'name': f'lsmmod:{block_id}'}]}]})
    for locale, name in (('es_es', 'Inodoro sin cubículo'), ('en_us', 'Standalone Toilet')):
        p = ASSETS / f'lang/{locale}.json'; values = json.loads(p.read_text()); values['block.lsmmod.standalone_toilet'] = name; write_json(p, values)
    p = DATA / 'minecraft/tags/block/mineable/pickaxe.json'; value = json.loads(p.read_text())
    value['values'] = list(dict.fromkeys(value['values']+['lsmmod:standalone_toilet']))
    write_json(p, value)


if __name__ == '__main__': main()
