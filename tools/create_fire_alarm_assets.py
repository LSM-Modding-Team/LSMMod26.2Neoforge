"""Generate a passive 6x8x2 px wall pull station using existing decoration materials."""
from resource_modules import module_read_text, module_write_text
import json
from PIL import Image, ImageDraw
from create_classroom_wall_assets import ASSETS, DATA, ROOT, model, write_json, save_texture

PARTS = [
    ([5, 4, 14.25, 11, 12, 16], "backpack_red", {}),
    ([5, 4, 14.1, 5.2, 12, 14.25], "paper_edge", {}),
    ([10.8, 4, 14.1, 11, 12, 14.25], "paper_edge", {}),
    ([5.2, 4, 14.1, 10.8, 4.2, 14.25], "paper_edge", {}),
    ([5.2, 11.8, 14.1, 10.8, 12, 14.25], "paper_edge", {}),
    ([5.2, 4.2, 14.125, 10.8, 11.8, 14.25], "backpack_red", {"north": "fire_alarm_front"}),
    ([5.8, 6.5, 14.0625, 10.2, 9.5, 14.125], "paper_edge", {}),
    ([6, 6.7, 14, 10, 9.3, 14.125], "backpack_zipper", {"north": "fire_alarm_pull"}),
]


def main():
    # 48x64 face: same eight texels per model pixel as the readable school clock.
    face = Image.new("RGB", (48, 64), (188, 52, 31))
    draw = ImageDraw.Draw(face)
    glyphs = {"F": ["1111", "1000", "1110", "1000", "1000"],
              "I": ["111", "010", "010", "010", "111"],
              "R": ["1110", "1001", "1110", "1010", "1001"],
              "E": ["1111", "1000", "1110", "1000", "1111"]}
    x = 4
    for letter in "FIRE":
        for y, row in enumerate(glyphs[letter]):
            for col, value in enumerate(row):
                if value == "1":
                    draw.rectangle((x+col*2, 4+y*2, x+col*2+1, 5+y*2), fill=(238, 238, 235))
        x += (len(glyphs[letter][0])+1)*2
    draw.ellipse((19, 1, 25, 7), fill=(165, 157, 126), outline=(88, 85, 72))
    draw.line((21, 4, 23, 4), fill=(56, 49, 44))
    draw.ellipse((35, 51, 45, 61), fill=(56, 49, 44), outline=(238, 238, 235))
    draw.ellipse((39, 55, 41, 57), fill=(20, 20, 20))
    save_texture("fire_alarm_front", face)
    pull = Image.new("RGB", (48, 32), (56, 49, 44))
    draw = ImageDraw.Draw(pull)
    # Tiny lettering remains pixel art, without relying on host font files.
    letters = {"P": ["110", "101", "110", "100", "100"],
               "U": ["101", "101", "101", "101", "111"],
               "L": ["100", "100", "100", "100", "111"],
               "D": ["110", "101", "101", "101", "110"],
               "O": ["111", "101", "101", "101", "111"],
               "W": ["101", "101", "101", "111", "101"],
               "N": ["101", "111", "111", "111", "101"]}
    for text, top in (("PULL", 5), ("DOWN", 12)):
        for i, letter in enumerate(text):
            for y, row in enumerate(letters[letter]):
                for x, value in enumerate(row):
                    if value == "1": draw.point((17+i*4+x, top+y), fill=(238, 238, 235))
    for x in (7, 40):
        draw.rectangle((x-1, 7, x+1, 16), fill=(238, 238, 235))
        draw.polygon([(x-4, 15), (x+4, 15), (x, 20)], fill=(238, 238, 235))
    draw.rectangle((2, 24, 45, 29), fill=(111, 75, 60))
    draw.line((2, 23, 45, 23), fill=(168, 168, 157))
    save_texture("fire_alarm_pull", pull)
    result = model(PARTS)
    result["textures"]["particle"] = "lsmmod:block/backpack_red"
    write_json(ASSETS/"models/block/fire_alarm.json", result)
    write_json(ASSETS/"blockstates/fire_alarm.json", {"variants": {
        f"facing={direction}": {"model": "lsmmod:block/fire_alarm", "y": angle}
        for direction, angle in (("north", 0), ("east", 90), ("south", 180), ("west", 270))}})
    write_json(ASSETS/"models/item/fire_alarm.json", {"parent": "lsmmod:block/fire_alarm",
        "display": {"gui": {"rotation": [15, 165, 0], "translation": [0, 0, -6], "scale": [1.6, 1.6, 1.6]}}})
    write_json(ASSETS/"items/fire_alarm.json", {"model": {"type": "minecraft:model", "model": "lsmmod:item/fire_alarm"}})
    write_json(DATA/"lsmmod/loot_table/blocks/fire_alarm.json", {"type": "minecraft:block", "pools": [{
        "rolls": 1, "conditions": [{"condition": "minecraft:survives_explosion"}],
        "entries": [{"type": "minecraft:item", "name": "lsmmod:fire_alarm"}]}]})
    for locale, title in (("es_es", "Alarma contra incendios"), ("en_us", "Fire Alarm")):
        path = ASSETS/f"lang/{locale}.json"
        values = json.loads(module_read_text(path, encoding="utf-8"))
        values["block.lsmmod.fire_alarm"] = title
        write_json(path, values)
    path = DATA/"minecraft/tags/block/mineable/pickaxe.json"
    values = json.loads(module_read_text(path))
    values["values"] = list(dict.fromkeys(values["values"]+["lsmmod:fire_alarm"]))
    write_json(path, values)
    # Keep physical geometry and generated artwork in agreement.
    path = ROOT/"src/main/java/net/nicomar2009/lsmmod/modules/wall_blocks/block/FireAlarmShapes.java"
    boxes = "\n".join("        {"+", ".join(str(v) for v in bounds)+"}," for bounds, _, _ in PARTS)
    module_write_text(path, "package net.nicomar2009.lsmmod.block;\n\n"
        "/** Generated by tools/create_fire_alarm_assets.py; north-facing, support at z=16. */\n"
        "public final class FireAlarmShapes {\n    public static final double[][] BOXES = {\n"+boxes+
        "\n    };\n\n    private FireAlarmShapes() {}\n}\n", encoding="utf-8")


if __name__ == "__main__":
    main()
