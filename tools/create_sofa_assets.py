"""Generate the burgundy modular sofa using the existing furniture mesh/drop helpers."""
from resource_modules import module_read_text, output_path
import json
import random

from PIL import Image
from create_bathroom_statue_assets import solid_model
from create_facility_expansion_assets import A, D, J, basic, write

ID = 'sofa'
SHAPES = ('straight', 'inner_left', 'inner_right', 'outer_left', 'outer_right')
TEXTURES = {
    'fabric': 'lsmmod:block/sofa_upholstery',
    'tufted': 'lsmmod:block/sofa_tufted',
    'legs': 'lsmmod:block/chair_black',
    'particle': '#fabric',
}


def turn_parts(parts, turns):
    result = []
    for part in parts:
        bounds, material = part[:2]
        overrides = dict(part[2]) if len(part) > 2 else {}
        x0, y0, z0, x1, y1, z1 = bounds
        for _ in range(turns):
            x0, z0, x1, z1 = 16-z1, x0, 16-z0, x1
            faces = {'north': 'east', 'east': 'south', 'south': 'west', 'west': 'north'}
            overrides = {faces.get(face, face): value for face, value in overrides.items()}
        result.append(([x0, y0, z0, x1, y1, z1], material, overrides))
    return result


def back(start=0, end=16):
    parts = [([start, 5.75, 0, end, 15.5, 1.75], 'fabric'),
             ([start, 15.5, .25, end, 15.75, 1.5], 'fabric')]
    # Three tiers of padded cushions with shallow bevels; no projecting armrests.
    for row in range(3):
        y = 7+row*2.875
        depth = 3.5-row*.5
        for x in range(start, end, 8):
            parts.extend([
                ([x, y, 1.75, x+8, y+2.625, depth-.375], 'fabric'),
                ([x+.125, y+.25, depth-.375, x+7.875, y+2.375, depth], 'fabric', {'south': 'tufted'}),
            ])
    return parts


def parts(shape):
    result = [([0, 2, 0, 16, 5.625, 16], 'fabric'),
              ([0, 5.625, .125, 16, 6.625, 15.875], 'fabric'),
              ([.125, 6.625, .375, 15.875, 7, 15.625], 'fabric')]
    for x in (1, 13.75):
        for z in (1, 13.75):
            result.append(([x, 0, z, x+1.25, 2, z+1.25], 'legs'))
    if shape == 'straight':
        result += back()
    elif shape == 'inner_left':
        result += back()+turn_parts(back(), 1)
    elif shape == 'inner_right':
        result += back()+turn_parts(back(), 3)
    elif shape == 'outer_left':
        result += back(8, 16)+turn_parts(back(0, 8), 1)
    elif shape == 'outer_right':
        result += back(0, 8)+turn_parts(back(8, 16), 3)
    else:
        raise ValueError(shape)
    return result


def model(geometry):
    value = solid_model(geometry)
    value.update(textures=TEXTURES, render_type='minecraft:solid')
    # Project world-space UVs on the clipped faces, preserving one texel/model pixel.
    for element in value['elements']:
        x0, y0, z0 = element['from']
        x1, y1, z1 = element['to']
        for face, surface in element['faces'].items():
            surface['uv'] = {
                'north': [16-x1, 16-y1, 16-x0, 16-y0],
                'south': [x0, 16-y1, x1, 16-y0],
                'east': [16-z1, 16-y1, 16-z0, 16-y0],
                'west': [z0, 16-y1, z1, 16-y0],
                'up': [x0, z0, x1, z1],
                'down': [x0, 16-z1, x1, 16-z0],
            }[face]
    return value


def main():
    rng = random.Random(390112)
    image = Image.new('RGB', (16, 16), '#390b12')
    for y in range(16):
        for x in range(16):
            delta = rng.choice((-1, 0, 0, 0, 0, 1))
            image.putpixel((x, y), tuple(c+delta for c in (57, 11, 18)))
    image.save(output_path(A/'textures/block/sofa_upholstery.png'))
    tufted = image.copy()
    # Small sewn dimples at the center of each real cushion, on its inward face only.
    for x in (4, 12):
        for y in (2, 5, 8):
            tufted.putpixel((x, y), (35, 5, 10))
            for dx, dy in ((-1, -1), (1, -1), (-1, 1), (1, 1)):
                tufted.putpixel((x+dx, y+dy), (48, 8, 14))
    tufted.save(output_path(A/'textures/block/sofa_tufted.png'))

    variants = {}
    grids = []
    for shape in SHAPES:
        geometry = parts(shape)
        write(A/f'models/block/sofa_{shape}.json', model(geometry))
        grids.append('        { // '+shape+'\n'+''.join(
            '            {'+', '.join(str(v) for v in part[0])+'},\n' for part in geometry)+'        }')
        for turns, facing in enumerate(('south', 'west', 'north', 'east')):
            variants[f'facing={facing},shape={shape}'] = {
                'model': 'lsmmod:block/sofa_'+shape, 'y': turns*90,
            }
    write(A/'blockstates/sofa.json', {'variants': variants})
    write(J/'modules/chairs/block/SofaShapes.java',
          'package net.nicomar2009.lsmmod.block;\n\n'
          '/** Generated by tools/create_sofa_assets.py; StairsShape order, native SOUTH facing. */\n'
          'final class SofaShapes {\n'
          '    static final double[][][] BOXES = {\n'+',\n'.join(grids)+'\n    };\n'
          '    private SofaShapes() {}\n}\n')
    write(A/'models/item/sofa.json', {
        'parent': 'lsmmod:block/sofa_straight',
        'display': {
            'gui': {'rotation': [30, 225, 0], 'scale': [.75, .75, .75]},
            'ground': {'translation': [0, 3, 0], 'scale': [.4, .4, .4]},
            'fixed': {'rotation': [0, 180, 0], 'scale': [.65, .65, .65]},
        },
    })
    basic(ID)
    for locale, name in (('es_es', 'Sillón granate'), ('en_us', 'Burgundy Sofa')):
        path = A/f'lang/{locale}.json'
        value = json.loads(module_read_text(path, encoding='utf-8'))
        value['block.lsmmod.sofa'] = name
        write(path, value)
    path = D/'minecraft/tags/block/mineable/axe.json'
    value = json.loads(module_read_text(path, encoding='utf-8'))
    value['values'] = list(dict.fromkeys(value['values']+['lsmmod:sofa']))
    write(path, value)


if __name__ == '__main__':
    main()
